package org.ghyura.cf.model;

import java.util.Collection;

/** "Did you mean ...?" for unknown commands, options and settings. */
public final class Suggestions {

    private Suggestions() {
    }

    /**
     * @return the candidate closest to {@code input} by edit distance, or {@code null} when none is within
     *         {@code maxDistance}; the first of equally close candidates wins, so the answer is deterministic
     */
    public static String closest(String input, Collection<String> candidates, int maxDistance) {
        String best = null;
        int bestDistance = maxDistance + 1;
        for (String candidate : candidates) {
            int d = editDistance(input, candidate);
            if (d < bestDistance) {
                bestDistance = d;
                best = candidate;
            }
        }
        return best;
    }

    /** Levenshtein distance: insertions, deletions and substitutions each cost 1. */
    public static int editDistance(String a, String b) {
        int[] previous = new int[b.length() + 1];
        int[] current = new int[b.length() + 1];
        for (int j = 0; j <= b.length(); j++) {
            previous[j] = j;
        }
        for (int i = 1; i <= a.length(); i++) {
            current[0] = i;
            for (int j = 1; j <= b.length(); j++) {
                int substitution = previous[j - 1] + (a.charAt(i - 1) == b.charAt(j - 1) ? 0 : 1);
                current[j] = Math.min(substitution, Math.min(previous[j] + 1, current[j - 1] + 1));
            }
            int[] swap = previous;
            previous = current;
            current = swap;
        }
        return previous[b.length()];
    }
}
