package org.ghyura.cf.compiler;

import java.lang.classfile.ClassFile;
import java.lang.classfile.ClassModel;
import java.lang.classfile.CodeElement;
import java.lang.classfile.MethodModel;
import java.lang.classfile.instruction.InvokeInstruction;
import java.util.ArrayList;
import java.util.List;
import java.util.Set;

/**
 * Finds calls in generated bytecode that would stop the whole virtual machine (System.exit, Runtime.exit,
 * Runtime.halt). One JVM cannot contain them (architecture D07), so a candidate that makes one is not run. This is a
 * check of the code as written: reflection or a library can still reach these methods, which is why execution stays
 * limited to trusted, cooperative code.
 */
public final class ForbiddenCalls {

    private static final Set<String> STOPPERS = Set.of("java/lang/System#exit", "java/lang/Runtime#exit", "java/lang/Runtime#halt");

    private ForbiddenCalls() {
    }

    /** Every forbidden call, as "Class.method calls owner#name", in class and code order. */
    public static List<String> find(CompiledClasses compiled) {
        List<String> found = new ArrayList<>();
        for (String name : compiled.names()) {
            ClassModel model = ClassFile.of().parse(compiled.bytecode(name));
            for (MethodModel method : model.methods()) {
                method.code().ifPresent(code -> {
                    for (CodeElement element : code) {
                        if (element instanceof InvokeInstruction invoke) {
                            String call = invoke.owner().asInternalName() + "#" + invoke.name().stringValue();
                            if (STOPPERS.contains(call)) {
                                found.add(name + "." + method.methodName().stringValue() + " calls " + call);
                            }
                        }
                    }
                });
            }
        }
        return found;
    }
}
