package org.ghyura.cf.campaign;

import org.ghyura.cf.model.Diagnostic;
import org.ghyura.cf.spi.SutCandidate;

import java.util.Collections;
import java.util.List;
import java.util.Map;
import java.util.Objects;
import java.util.Optional;
import java.util.TreeMap;

/**
 * Candidates that were not generated by this build, such as an imported legacy hand-over: they run through the same
 * execution, results and summary as generated ones, with nothing planned or assembled.
 *
 * @param source       where they come from (the manifest path)
 * @param digest       a digest of that source, standing for the plan digest in samples and the summary
 * @param candidates   the candidates in execution order
 * @param verdictNames names of verdict codes (FW_CUSTOM_VAR messages)
 * @param arguments    arguments of generated Java candidates
 * @param runFirstOnce a Java source run once before the candidates, if any
 * @param diagnostics  what the import noticed
 */
public record ImportedCandidates(String source, String digest, List<? extends SutCandidate> candidates, Map<Integer, String> verdictNames,
                                 List<String> arguments, Optional<String> runFirstOnce, List<Diagnostic> diagnostics) {
    public ImportedCandidates {
        Objects.requireNonNull(source, "source");
        Objects.requireNonNull(digest, "digest");
        candidates = List.copyOf(candidates);
        verdictNames = Collections.unmodifiableMap(new TreeMap<>(verdictNames));
        arguments = List.copyOf(arguments);
        Objects.requireNonNull(runFirstOnce, "runFirstOnce");
        diagnostics = List.copyOf(diagnostics);
    }
}
