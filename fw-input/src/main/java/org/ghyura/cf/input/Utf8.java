package org.ghyura.cf.input;

import org.ghyura.cf.model.Diagnostic;
import org.ghyura.cf.model.ErrorCode;
import org.ghyura.cf.model.FrameworkException;
import org.ghyura.cf.model.SourceLocation;

import java.nio.ByteBuffer;
import java.nio.charset.CharacterCodingException;
import java.nio.charset.CodingErrorAction;
import java.nio.charset.StandardCharsets;

/** Strict UTF-8 decoding of an input document: a byte order mark is dropped, malformed bytes are an error. */
final class Utf8 {

    private Utf8() {
    }

    static String decode(InputSource source) {
        byte[] bytes = source.view();
        int offset = bytes.length >= 3 && (bytes[0] & 0xFF) == 0xEF && (bytes[1] & 0xFF) == 0xBB && (bytes[2] & 0xFF) == 0xBF
                ? 3 : 0;
        try {
            return StandardCharsets.UTF_8.newDecoder()
                    .onMalformedInput(CodingErrorAction.REPORT)
                    .onUnmappableCharacter(CodingErrorAction.REPORT)
                    .decode(ByteBuffer.wrap(bytes, offset, bytes.length - offset)).toString();
        } catch (CharacterCodingException e) {
            throw new FrameworkException(Diagnostic.error(ErrorCode.INPUT_MALFORMED,
                    "the input is not valid UTF-8", SourceLocation.of(source.name())), e);
        }
    }

    /** The label recorded as the workbook's source: {@code format:fileName}, as the legacy readers logged it. */
    static String displayName(String format, String origin) {
        int slash = Math.max(origin.lastIndexOf('/'), origin.lastIndexOf('\\'));
        return format + ":" + (slash >= 0 ? origin.substring(slash + 1) : origin);
    }
}
